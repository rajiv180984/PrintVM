package com.first.test.model;

public class PrinterDetails {

	private String printerId;
	private String model;
	private String make;
	private String papercapacity;
	private String cartidgeType;
	public String getPrinterId() {
		return printerId;
	}
	public void setPrinterId(String printerId) {
		this.printerId = printerId;
	}
	public String getModel() {
		return model;
	}
	public void setModel(String model) {
		this.model = model;
	}
	public String getMake() {
		return make;
	}
	public void setMake(String make) {
		this.make = make;
	}
	public String getPapercapacity() {
		return papercapacity;
	}
	public void setPapercapacity(String papercapacity) {
		this.papercapacity = papercapacity;
	}
	public String getCartidgeType() {
		return cartidgeType;
	}
	public void setCartidgeType(String cartidgeType) {
		this.cartidgeType = cartidgeType;
	}
	
	

}
